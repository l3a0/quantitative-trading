@dataclass(frozen=True)
class SharpeGap:
    """Two annualised Sharpe ratios on the same days, their gap and its standard error.

    ``gap`` is ``a_sharpe − b_sharpe``. ``correlation`` is the Pearson
    correlation of the two daily series, and ``standard_error`` is the gap's,
    annualised by the same √252 as the ratios.
    """

    a_sharpe: float
    b_sharpe: float
    gap: float
    correlation: float
    standard_error: float
    days: int

    @property
    def z(self) -> float:
        """The gap in standard errors. NaN when both are 0, as for one series against itself."""
        if self.standard_error == 0:
            return math.nan if self.gap == 0 else math.copysign(math.inf, self.gap)
        return self.gap / self.standard_error

    @property
    def beyond_noise(self) -> bool:
        """Whether the gap is more than :data:`NOISE_MULTIPLE` standard errors from 0."""
        return abs(self.gap) > NOISE_MULTIPLE * self.standard_error


def sharpe_gap(a: np.ndarray, b: np.ndarray) -> SharpeGap:
    """The gap between two Sharpe ratios and its standard error, Memmel's (2003) test.

    Jobson and Korkie (1981) derived the variance of the difference between
    two Sharpe ratios measured on the same days, and Memmel (2003) corrected
    it. With daily Sharpe ratios ``s_a`` and ``s_b``, their series' Pearson
    correlation ``ρ`` and ``T`` days::

        Var(ŝa − ŝb) = (1/T) · [2(1 − ρ) + ½(s_a² + s_b² − 2 s_a s_b ρ²)]

    Each daily ratio is ``mean / std`` with the deviation dividing by n − 1,
    as :func:`chan.khandani_lo.plain_sharpe` does. The annualised ratios are
    ``plain_sharpe`` itself, so on a series with no NaN ``a_sharpe`` equals
    :func:`chan.khandani_lo.chan_sharpe` exactly, and the standard error is
    the daily one times √252.

    The correlation is what makes the test fit two books on the same days. Two
    reversals on two universes earn on the same market moves, so their daily
    profits move together, and a gap between correlated series has a smaller
    standard error than one between independent series. A Sharpe ratio does not
    change when a book is scaled, so two books of different size need no
    matching first, which is the step ``chan.risk_parity``'s test of a mean
    difference needs and this one does not.

    The formula assumes the daily profits are independent from day to day and
    jointly normal. A reversal's daily profits are neither, so the standard
    error is an approximation, and a reading of it says so.

    It pairs the two series by position, so the caller pairs the dates first,
    the way :func:`same_days` does for two :class:`chan.khandani_lo.Reversal`
    runs. Both series must hold the same number of days, each a finite number,
    and each must vary. It refuses otherwise rather than pairing or skipping
    days, because a pairing it invented would be a different test. A series
    with no spread has no Sharpe ratio, and its rounding error alone would set
    the standard error. ``np.corrcoef`` already holds ``ρ`` to [−1, 1]. The
    clip stays as a guard against a numpy that does not, since a ``ρ`` past 1
    could take the variance of one series against itself below 0.
    """
    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)
    if a.shape != b.shape or a.ndim != 1:
        raise ValueError(
            f"sharpe_gap pairs two series day by day, and was handed {a.shape} and {b.shape}"
        )
    if len(a) < 3:
        raise ValueError(f"sharpe_gap needs at least 3 days, and was handed {len(a)}")
    if not (np.isfinite(a).all() and np.isfinite(b).all()):
        raise ValueError("sharpe_gap takes two series with every day finite")
    if np.ptp(a) == 0 or np.ptp(b) == 0:
        raise ValueError("sharpe_gap takes two series that vary, and one holds a single value")
    days = len(a)
    s_a = a.mean() / a.std(ddof=1)
    s_b = b.mean() / b.std(ddof=1)
    rho = float(np.clip(np.corrcoef(a, b)[0, 1], -1.0, 1.0))
    variance = (2 * (1 - rho) + 0.5 * (s_a**2 + s_b**2 - 2 * s_a * s_b * rho**2)) / days
    a_sharpe, b_sharpe = plain_sharpe(a), plain_sharpe(b)
    return SharpeGap(
        a_sharpe=a_sharpe,
        b_sharpe=b_sharpe,
        gap=a_sharpe - b_sharpe,
        correlation=rho,
        standard_error=float(math.sqrt(TRADING_DAYS * variance)),
        days=days,
    )


def points_chans_way(before_costs_largest_to_smallest: Sequence[float]) -> bool:
    """Whether one price's before-cost figures rise strictly as capitalisation falls.

    Handed the S&P 500 and then the S&P 600 it is the declaration's pairwise
    reading. Handed the S&P 500, the S&P 400 and the S&P 600, in that order,
    it is the order issue 303 reads, where every adjacent pair must rise.
    """
    figures = [float(f) for f in before_costs_largest_to_smallest]
    if len(figures) < 2:
        raise ValueError(f"an order needs at least two universes, and was handed {len(figures)}")
    if not all(math.isfinite(f) for f in figures):
        raise ValueError(f"an order reads finite figures, and was handed {figures}")
    return all(larger < smaller for larger, smaller in zip(figures[:-1], figures[1:], strict=True))


def direction(
    closes_largest_to_smallest: Sequence[float], opens_largest_to_smallest: Sequence[float]
) -> str:
    """The declaration's word for both prices read together.

    Pointing the way Chan says at both prices, mixed at one, and pointing
    against it at neither. The declaration defined those words for two
    universes, so each price must hold exactly two figures, the S&P 500's and
    then the S&P 600's. Issue 303 reads three universes with
    :func:`points_chans_way` and its own words.
    """
    for price, figures in (
        ("closes", closes_largest_to_smallest),
        ("opens", opens_largest_to_smallest),
    ):
        if len(figures) != 2:
            raise ValueError(
                f"direction reads two universes at each price, and the {price} held {len(figures)}"
            )
    held = points_chans_way(closes_largest_to_smallest) + points_chans_way(
        opens_largest_to_smallest
    )
    return {2: POINTING_CHANS_WAY, 1: MIXED, 0: POINTING_AGAINST}[held]


@dataclass(frozen=True)
class Comparison:
    """Rule B on both files at both prices, and the two before-cost gaps.

    ``closes_gap`` and ``opens_gap`` are :func:`sharpe_gap` with the S&P 600's
    profit before costs as ``a`` and the S&P 500's as ``b``, so a positive gap
    is the small caps ahead.
    """

    small_closes: Reversal
    small_opens: Reversal
    large_closes: Reversal
    large_opens: Reversal
    closes_gap: SharpeGap
    opens_gap: SharpeGap

    @property
    def reading(self) -> str:
        return direction(
            (self.large_closes.before_costs, self.small_closes.before_costs),
            (self.large_opens.before_costs, self.small_opens.before_costs),
        )


def same_days(small: Reversal, large: Reversal) -> None:
    """Refuse two runs whose windows hold different days, since the gap pairs them by day."""
    if small.days.equals(large.days):
        return
    if len(small.days) != len(large.days):
        differ = f"{len(small.days)} against {len(large.days)}"
    else:
        first = int(np.flatnonzero(small.days != large.days)[0])
        differ = f"first differing at {small.days[first].date()} against {large.days[first].date()}"
    raise ValueError(
        f"the two files' windows hold different trading days, {differ}, "
        "so their profits cannot be paired by day"
    )


def comparison(
    small_closes: pd.DataFrame,
    small_opens: pd.DataFrame,
    large_closes: pd.DataFrame,
    large_opens: pd.DataFrame,
) -> Comparison:
    """Run rule B on four frames already read and pair each price's two runs."""
    runs = {
        "small_closes": reversal(small_closes),
        "small_opens": reversal(small_opens),
        "large_closes": reversal(large_closes),
        "large_opens": reversal(large_opens),
    }
    same_days(runs["small_closes"], runs["large_closes"])
    same_days(runs["small_opens"], runs["large_opens"])
    return Comparison(
        **runs,
        closes_gap=sharpe_gap(runs["small_closes"].pnl, runs["large_closes"].pnl),
        opens_gap=sharpe_gap(runs["small_opens"].pnl, runs["large_opens"].pnl),
    )


def _read(data_dir: Path | None):
    small_members, small_closes = load_panel(SOURCE_FILE, data_dir=data_dir)
    _, small_opens = load_panel(SOURCE_FILE, field="Open", data_dir=data_dir)
    large_members, large_closes = load_panel(LARGE_CAP_FILE, data_dir=data_dir)
    _, large_opens = load_panel(LARGE_CAP_FILE, field="Open", data_dir=data_dir)
    frames = (small_closes, small_opens, large_closes, large_opens)
    return small_members, large_members, frames


def compare(data_dir: Path | None = None) -> Comparison:
    """Read both files' closes and opens and run the comparison."""
    _, _, frames = _read(data_dir)
    return comparison(*frames)


def _noise(gap: SharpeGap) -> str:
    word = "beyond" if gap.beyond_noise else "within"
    return f"{word} one year's noise"


def report(small_members, large_members, result: Comparison) -> None:
    """Print both files, the six pairs, the two standard errors and the reading."""
    cost = f"{ONE_WAY_COST * 1e4:.0f} bp a side"
    days = result.small_closes.days
    print("Khandani and Lo's linear reversal on Chan's S&P 600 file, beside his S&P 500 file")
    print(f"  S&P 600  {panel_line(small_members)}")
    print(f"  S&P 500  {panel_line(large_members)}")
    print(
        f"  window   {days[0].date()} to {days[-1].date()}, {len(days)} trading days, "
        "the same days in both files"
    )
    print("  rule     rule B, Example 3.7's MATLAB, on the closes and on the opens")
    print(f"  Sharpe   sqrt({TRADING_DAYS}) * mean / std, no risk-free rate")
    print()
    print(f"  {'Price and specification':<66} {'S&P 600':>8}  {'S&P 500':>8}  {'Gap':>8}")
    specifications = (
        ("before costs", "before_costs"),
        (f"after {cost}, first day uncharged, NaN zero-filled", "after_costs"),
        (f"after {cost}, first day charged", "after_costs_charged"),
    )
    for price, small, large in (
        ("Closes", result.small_closes, result.large_closes),
        ("Opens", result.small_opens, result.large_opens),
    ):
        for label, field in specifications:
            a, b = getattr(small, field), getattr(large, field)
            print(f"  {price + ', ' + label:<66} {a:>8.4f}  {b:>8.4f}  {a - b:>+8.4f}")
    print()
    print("  Before-cost gaps against Memmel's (2003) standard error, iid normal days assumed:")
    for price, gap in (("Closes", result.closes_gap), ("Opens", result.opens_gap)):
        print(
            f"    {price:<7} gap {gap.gap:+.4f}, standard error {gap.standard_error:.4f}, "
            f"correlation {gap.correlation:.4f}, z {gap.z:+.4f}, {_noise(gap)}"
        )
    print(f"  Reading, declared before any figure: {result.reading}.")
    print(
        f"    The S&P 600 higher before costs at both prices is {POINTING_CHANS_WAY}, "
        f"at one is {MIXED}, at neither is {POINTING_AGAINST}."
    )
    print(f"    A gap beyond noise is more than {NOISE_MULTIPLE:g} standard errors from 0.")
    print()
    print(
        f"  Khandani and Lo report {BOOK_KHANDANI_LO:.2f} for 2006 on their own universe, "
        "printed and judged against nothing."
    )
    print(
        "  Both files hold only survivors, the S&P 600 as of 2008-01-14 and the S&P 500 "
        "as of 2007-11-23."
    )
    print(
        f"  Both files pay the same {cost}, while small caps cost more to trade, "
        "so the after-cost figures flatter the S&P 600."
    )
    print(
        "  The S&P 600 holds no microcaps, which Chan's sentence names beside small caps, "
        "so no figure here speaks for them."
    )
    print(
        "  EXPLORATORY. A rule Chan published, run on data he left as an exercise, "
        "so no figure carries a verdict."
    )


def run(data_dir: Path | None = None) -> Comparison:
    """Read both files, run the comparison, and print the report."""
    small_members, large_members, frames = _read(data_dir)
    result = comparison(*frames)
    report(small_members, large_members, result)
    return result


def main() -> None:
    argparse.ArgumentParser(
        description="Khandani and Lo's linear reversal on Chan's S&P 600 file, "
        "beside his S&P 500 file"
    ).parse_args()
    try:
        run()
    except VintageUnavailable as unavailable:
        # A refusal that names the source is worth nothing at the bottom of a
        # pandas traceback, so it reaches the reader as one line, the way
        # chan.khandani_lo.main does it.
        raise SystemExit(str(unavailable)) from unavailable


if __name__ == "__main__":
    main()
