"""Khandani and Lo's reversal on the S&P 400, between Chan's S&P 500 and S&P 600 files.

Chan explains the reversal's collapse on the S&P 500, from Khandani and Lo's
4.47 to his 0.25, by saying "most of the returns are generated by small and
microcap stocks", at Kindle location 2137. Example 3.8 then leaves the
S&P 400 and the S&P 600 as an exercise, at location 2236 on p. 78 of the
revised edition. :mod:`chan.khandani_lo_small_caps` runs the S&P 600 half on
his own file. This module runs the mid-cap half and reads the three
universes as one ladder, so the test of the explanation has three points
rather than two.

**What runs.** Rule B, which is :func:`chan.khandani_lo.reversal` unchanged,
on four panels at two prices each.

1. The S&P 500 is ``load_panel("SPX_20071123.mat")``, and the same call with
   ``field="Open"``, exactly as :mod:`chan.khandani_lo_small_caps` reads it.
2. The S&P 600 is ``load_panel("IJR_20080114.mat")`` the same two ways.
3. The S&P 400 is :data:`chan.sp400_panel.IJH_PANEL`, the 285 members of
   IJH's 2007-12-31 schedule that pass the price check and have a 2006 row
   before the vendor's cut-off, priced from the ``sp400`` cross-section.
4. The control is :data:`chan.sp400_panel.CONTROL`, the 385 members of IJR's
   2007-12-31 schedule chosen by the same rule, priced from ``sp600``.

Every run covers 2006-01-03 to 2006-12-29, with 5 basis points on each side
of a change in weight and ``√252 · mean / std`` with no risk-free rate. The
closes on the two archive panels are Alpha Vantage's ``adjusted_close``. The
vendor adjusts only the close, so an open is ``open × adjusted_close / close``
on the same day, which :func:`chan.sp400_panel.frames` computes. The archive
frames are cut to :data:`FRAME_START` to :data:`FRAME_END`, the span the
flagged days were read over. Rule B reads only a day and the one before it,
so the cut moves no figure inside the window.

**The vintages.** Chan's two files are the S&P 500 as it stood on 2007-11-23
and the S&P 600 as it stood on 2008-01-14, carried backwards. The two archive
panels are every holding of one filing, iShares Trust's N-Q for 2007-12-31,
accession ``0001193125-08-043324``, read from Alpha Vantage's daily bars
downloaded on 2026-10-11 for ``sp400`` and on 2026-10-05 or 2026-10-11 for
``sp600``. So the S&P 400 figure comes from another vendor and another
download decade than both of its neighbours. The control measures what that
does: it builds the S&P 600 exactly the way the S&P 400 panel is built and
reads it against Chan's S&P 600 file.

**Every figure is about survivors.** Chan's files hold the stocks still in
each index on their dates. The archive panels hold 71.1% of IJH's holdings by
count and 64.0% of IJR's. They leave out a holding that fails the price check,
whose series starts on Alpha Vantage's 2006-12-28 cut-off, or that has no 2006
row, so what they leave out follows how the vendor serves each ticker today.
It includes companies bought or failed after 2007, such as Cephalon and
IndyMac, and :mod:`chan.sp400_panel` says which group each member falls in.
Which way that moves a reversal is untested, and nothing here measures how big
it is on the S&P 400. The control's gap holds the same selection's effect on
the S&P 600 only, mixed with the change of vendor and download decade.

**The reading was declared before any figure was computed.** Issue 249's
[comparison declaration](https://github.com/l3a0/quantitative-trading/issues/249#issuecomment-6104832067)
covers the S&P 600, and its section for issue 303 extends it to a third
universe. [Issue 303](https://github.com/l3a0/quantitative-trading/issues/303)
declares its own words for an order that fails, in its body and in
[the declarations before the run](https://github.com/l3a0/quantitative-trading/issues/303#issuecomment-6116653928).

1. **The order at each price, before costs.** :func:`order` reads S&P 500
   below S&P 400 below S&P 600 as :data:`HOLDS`, the reverse as
   :data:`REVERSED`, and anything else as :data:`PARTIAL`.
   :func:`chan.khandani_lo_small_caps.points_chans_way` decides both, handed
   the figures largest index first and then the other way round.
2. **Both prices together.** :func:`reading` gives
   :data:`chan.khandani_lo_small_caps.POINTING_CHANS_WAY` when the order holds
   at both, :data:`chan.khandani_lo_small_caps.POINTING_AGAINST` when it is
   fully reversed at both, and :data:`chan.khandani_lo_small_caps.MIXED`
   otherwise. :func:`pair_directions` then names each adjacent pair's
   direction at each price, so a reader sees which step of the ladder broke.
3. **Size.** Each adjacent pair at each price gets
   :func:`chan.khandani_lo_small_caps.sharpe_gap` on the before-cost daily
   profits, after :func:`chan.khandani_lo_small_caps.same_days` confirms the
   two runs hold the same days. A gap more than twice its standard error reads
   as larger than one year's noise. The size reading adds no verdict.
4. **The control.** At each price its gap is its before-cost figure less
   Chan's S&P 600's. If that gap, in absolute value, exceeds the S&P 400
   figure's distance to its nearer neighbour at either price,
   :func:`separable` is false and the reading is :data:`NOT_SEPARABLE`, with
   no direction read.

**The flagged days.** :func:`chan.series.scale_breaks` flags five days on held
members' own prices over 2005-12-01 to 2006-12-31, each on the close and on
the open. They were classified from prices and outside evidence before any
strategy figure was computed.

1. KCI on 2006-08-04, in the S&P 400, is a real traded move after a jury
   verdict, so it stays in. :data:`KEPT_FLAGGED_DAYS` names it.
2. CORSQ on 2006-05-19 and ZD on 2006-05-25, in the control, are 2-for-1
   splits the vendor left unadjusted. Each member's return on that day is set
   to NaN on both prices. :data:`SPLIT_DAYS` names them.
3. MAG on 2006-01-10, in the control, is one bad print, at 1.295 between
   closes of 3.32 and 3.38, on the close and on the open. ``scale_breaks``
   flags it and the day after. Its price that day is set to NaN on both,
   which makes the returns on 2006-01-10 and 2006-01-11 NaN.
   :data:`BAD_PRINTS` names it.

:func:`exclude` applies the last two, and the run reports the control with
and without them. The run with them is primary. The S&P 400 panel has nothing
excluded, so it has one set of figures.

**This module does not call the scale-break guard.**
:func:`chan.series.refuse_window_crossing_a_break` would stop the run over the
days above, and each of them was classified before the run and handled by the
declared rule instead. Refusing would withhold a run whose treatment of those
days was already decided in writing. Chan's two files are read as
:mod:`chan.khandani_lo_small_caps` reads them, and its docstring says why that
module does not call the guard either.

**EXPLORATORY.** The run applies a rule Chan published, unchanged, to the
mid-cap and small-cap stocks his exercise names, and Chan prints no figure for
either universe, so no figure carries a verdict. A reading that points the way
Chan says earns a registered test on data the run has not seen.

```bash
QT_ARCHIVE_DIR=/path/to/archive uv run python -m chan.khandani_lo_mid_caps
```
"""

