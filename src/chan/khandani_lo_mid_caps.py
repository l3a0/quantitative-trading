# --- The readings ---------------------------------------------------------------


def order(before_costs_largest_to_smallest: Sequence[float]) -> str:
    """One price's order: :data:`HOLDS`, :data:`REVERSED` or :data:`PARTIAL`.

    The figures arrive largest index first. The order holds when they rise
    strictly as capitalisation falls, which is
    :func:`chan.khandani_lo_small_caps.points_chans_way`. It is fully reversed
    when they fall strictly, which is the same function handed them the other
    way round. A tie at any step is neither, so it reads as partial.
    """
    figures = list(before_costs_largest_to_smallest)
    if points_chans_way(figures):
        return HOLDS
    if points_chans_way(figures[::-1]):
        return REVERSED
    return PARTIAL


def pair_directions(before_costs_largest_to_smallest: Sequence[float]) -> tuple[bool, ...]:
    """Whether each adjacent pair rises as capitalisation falls, largest pair first.

    Handed the S&P 500, the S&P 400 and the S&P 600, the first entry is the
    S&P 400 against the S&P 500 and the second the S&P 600 against the S&P 400.
    """
    figures = list(before_costs_largest_to_smallest)
    if len(figures) < 2:
        raise ValueError(f"a pair needs at least two universes, and was handed {len(figures)}")
    return tuple(points_chans_way(figures[i : i + 2]) for i in range(len(figures) - 1))


def reading(
    closes_largest_to_smallest: Sequence[float], opens_largest_to_smallest: Sequence[float]
) -> str:
    """Issue 303's word for both prices read together.

    The order holding at both prices points the way Chan says, the order fully
    reversed at both points against it, and anything else is mixed.
    """
    orders = {order(closes_largest_to_smallest), order(opens_largest_to_smallest)}
    if orders == {HOLDS}:
        return POINTING_CHANS_WAY
    if orders == {REVERSED}:
        return POINTING_AGAINST
    return MIXED


def nearer_step(before_costs_largest_to_smallest: Sequence[float]) -> float:
    """The middle figure's distance to its nearer neighbour, in Sharpe ratio."""
    larger, middle, smaller = (float(f) for f in before_costs_largest_to_smallest)
    return min(abs(middle - larger), abs(middle - smaller))


def separable(control_gaps: Sequence[float], nearer_steps: Sequence[float]) -> bool:
    """Whether the control's gap stays within the S&P 400's nearer step at every price.

    Both arguments hold one value per price, in the same order. The ordering
    is not separable from how the panel was built when the control's gap
    exceeds, in absolute value, the step at any price.
    """
    if len(control_gaps) != len(nearer_steps):
        raise ValueError(
            f"one control gap per price, and was handed {len(control_gaps)} gaps "
            f"against {len(nearer_steps)} steps"
        )
    return all(abs(gap) <= step for gap, step in zip(control_gaps, nearer_steps, strict=True))


# --- The exclusions ---------------------------------------------------------------


def split_column(symbol: str, day: str) -> str:
    """The name a split member's prices from its split day on are carried under."""
    return f"{symbol} from {day}"


def without_bad_prints(frame: pd.DataFrame, prints: Mapping[str, str]) -> pd.DataFrame:
    """The frame with each named price set to NaN.

    Refused where the price is not in the frame or is not a number already,
    because an exclusion that changes nothing is one the reader cannot see.
    """
    out = frame.copy()
    for symbol, day in prints.items():
        when = pd.Timestamp(day)
        if symbol not in out.columns or when not in out.index or pd.isna(out.at[when, symbol]):
            raise ValueError(f"{symbol} has no price on {day} to exclude")
        out.at[when, symbol] = math.nan
    return out


def split_at(frame: pd.DataFrame, splits: Mapping[str, str]) -> pd.DataFrame:
    """The frame with each named member's return on its split day made NaN, prices kept.

    Rule B reads prices, so the return is made NaN by carrying the member
    under two columns. The member's own column keeps its prices before the
    day, and :func:`split_column` holds them from the day on. Neither column
    then has a return on the split day, while every other return, every
    price and each day's count of priced members stay what they were. Rule B
    weights a return that is not finite at 0, so the member closes its
    position on the split day and opens it again the day after.
    """
    out = frame.copy()
    for symbol, day in splits.items():
        when = pd.Timestamp(day)
        if symbol not in out.columns or when not in out.index:
            raise ValueError(f"{symbol} has no row on {day} to split at")
        prices = out[symbol]
        before = prices.loc[: when - pd.Timedelta(days=1)]
        if before.dropna().empty or pd.isna(prices.at[when]):
            raise ValueError(f"{symbol} has no return on {day} to exclude")
        after = prices.where(prices.index >= when)
        out[symbol] = prices.where(prices.index < when)
        out.insert(out.columns.get_loc(symbol) + 1, split_column(symbol, day), after)
    return out


def exclude(frame: pd.DataFrame) -> pd.DataFrame:
    """The control's frame with :data:`BAD_PRINTS` and :data:`SPLIT_DAYS` excluded."""
    return split_at(without_bad_prints(frame, BAD_PRINTS), SPLIT_DAYS)


# --- The frames -------------------------------------------------------------------


def held(
    panel: Panel, *, directory: Path | None = None
) -> tuple[list[str], pd.DataFrame, pd.DataFrame]:
    """The tickers a 2006 run holds, sorted, and their adjusted closes and opens.

    The members are :func:`chan.sp400_panel.panel_keys`'s, and both frames
    are cut to :data:`FRAME_START` to :data:`FRAME_END`.
    """
    rows = sp400_panel.load(panel)
    adjusted, opens, adjusted_opens = sp400_panel.frames(panel, rows, directory=directory)
    histories = sp400_panel.history(rows, adjusted, opens, sp400_panel.calendar())
    kept = set(sp400_panel.panel_keys(histories))
    tickers = sorted(entry.ticker for entry in histories if entry.key in kept)
    span = slice(FRAME_START, FRAME_END)
    return tickers, adjusted.loc[span, tickers], adjusted_opens.loc[span, tickers]


@dataclass(frozen=True)
class Frames:
    """Every frame the run reads, raw, by universe and price."""

    large_closes: pd.DataFrame
    large_opens: pd.DataFrame
    mid_closes: pd.DataFrame
    mid_opens: pd.DataFrame
    small_closes: pd.DataFrame
    small_opens: pd.DataFrame
    control_closes: pd.DataFrame
    control_opens: pd.DataFrame


def read(data_dir: Path | None = None, directory: Path | None = None):
    """Chan's two files from ``data_dir`` and the archive panels from ``directory``.

    Returns the two files' members, the two panels' held tickers, and the
    :class:`Frames`.
    """
    large_members, large_closes = load_panel(LARGE_CAP_FILE, data_dir=data_dir)
    _, large_opens = load_panel(LARGE_CAP_FILE, field="Open", data_dir=data_dir)
    small_members, small_closes = load_panel(SMALL_CAP_FILE, data_dir=data_dir)
    _, small_opens = load_panel(SMALL_CAP_FILE, field="Open", data_dir=data_dir)
    mid, mid_closes, mid_opens = held(IJH_PANEL, directory=directory)
    control, control_closes, control_opens = held(CONTROL, directory=directory)
    frames = Frames(
        large_closes=large_closes,
        large_opens=large_opens,
        mid_closes=mid_closes,
        mid_opens=mid_opens,
        small_closes=small_closes,
        small_opens=small_opens,
        control_closes=control_closes,
        control_opens=control_opens,
    )
    return (large_members, small_members), (mid, control), frames


# --- The run ----------------------------------------------------------------------


@dataclass(frozen=True)
class Ladder:
    """One price's four runs and the control without its exclusions, with their gaps.

    ``mid_gap`` is :func:`sharpe_gap` with the S&P 400's before-cost profit as
    ``a`` and the S&P 500's as ``b``, and ``small_gap`` the S&P 600's against
    the S&P 400's, so a positive gap is the smaller index ahead.
    ``control_gap`` is the control against Chan's S&P 600, and
    ``control_gap_unexcluded`` the same without the exclusions.
    """

    large: Reversal
    mid: Reversal
    small: Reversal
    control: Reversal
    control_unexcluded: Reversal
    mid_gap: SharpeGap
    small_gap: SharpeGap
    control_gap: SharpeGap
    control_gap_unexcluded: SharpeGap

    @property
    def figures(self) -> tuple[float, float, float]:
        """The three universes' before-cost figures, largest index first."""
        return (self.large.before_costs, self.mid.before_costs, self.small.before_costs)

    @property
    def order(self) -> str:
        return order(self.figures)

    @property
    def nearer_step(self) -> float:
        return nearer_step(self.figures)


def ladder(
    large: pd.DataFrame,
    mid: pd.DataFrame,
    small: pd.DataFrame,
    control: pd.DataFrame,
) -> Ladder:
    """Rule B on one price's four frames, the control with and without its exclusions."""
    runs = {
        "large": reversal(large),
        "mid": reversal(mid),
        "small": reversal(small),
        "control": reversal(exclude(control)),
        "control_unexcluded": reversal(control),
    }
    for name in ("mid", "small", "control", "control_unexcluded"):
        same_days(runs[name], runs["large"])
    return Ladder(
        **runs,
        mid_gap=sharpe_gap(runs["mid"].pnl, runs["large"].pnl),
        small_gap=sharpe_gap(runs["small"].pnl, runs["mid"].pnl),
        control_gap=sharpe_gap(runs["control"].pnl, runs["small"].pnl),
        control_gap_unexcluded=sharpe_gap(runs["control_unexcluded"].pnl, runs["small"].pnl),
    )


@dataclass(frozen=True)
class MidCapComparison:
    """Both prices' ladders and what they read as."""

    closes: Ladder
    opens: Ladder

    @property
    def separable(self) -> bool:
        """Whether the control's gap, with the exclusions, stays within the nearer step."""
        ladders = (self.closes, self.opens)
        return separable(
            [each.control_gap.gap for each in ladders], [each.nearer_step for each in ladders]
        )

    @property
    def separable_unexcluded(self) -> bool:
        """The same test on the control without its exclusions, reported and never read."""
        ladders = (self.closes, self.opens)
        return separable(
            [each.control_gap_unexcluded.gap for each in ladders],
            [each.nearer_step for each in ladders],
        )

    @property
    def reading(self) -> str:
        if not self.separable:
            return NOT_SEPARABLE
        return reading(self.closes.figures, self.opens.figures)


def comparison(frames: Frames) -> MidCapComparison:
    """Run both prices' ladders on frames already read."""
    return MidCapComparison(
        closes=ladder(
            frames.large_closes, frames.mid_closes, frames.small_closes, frames.control_closes
        ),
        opens=ladder(
            frames.large_opens, frames.mid_opens, frames.small_opens, frames.control_opens
        ),
    )


# --- The report -------------------------------------------------------------------


def _noise(gap: SharpeGap) -> str:
    word = "beyond" if gap.beyond_noise else "within"
    return f"{word} one year's noise"


def _gap_line(label: str, gap: SharpeGap) -> str:
    return (
        f"    {label:<34} gap {gap.gap:+.4f}, standard error {gap.standard_error:.4f}, "
        f"correlation {gap.correlation:.4f}, z {gap.z:+.4f}, {_noise(gap)}"
    )


def report(members, held_tickers, result: MidCapComparison) -> None:
    """Print the four panels, every figure, the gaps, the control and the reading."""
    large_members, small_members = members
    mid, control = held_tickers
    cost = f"{ONE_WAY_COST * 1e4:.0f} bp a side"
    days = result.closes.large.days
    print("Khandani and Lo's linear reversal on the S&P 400, between Chan's S&P 500 and S&P 600")
    print(f"  S&P 500  {panel_line(large_members)}")
    print(
        f"  S&P 400  {len(mid)} of IJH's 401 holdings on 2007-12-31, "
        "sp400 cross-section, Alpha Vantage, downloaded 2026-10-11"
    )
    print(f"  S&P 600  {panel_line(small_members)}")
    print(
        f"  control  {len(control)} of IJR's 602 holdings on 2007-12-31, built as the S&P 400 "
        "panel is, sp600 cross-section, Alpha Vantage"
    )
    print(
        f"  window   {days[0].date()} to {days[-1].date()}, {len(days)} trading days, "
        "the same days in all four"
    )
    print("  rule     rule B, Example 3.7's MATLAB, on the closes and on the opens")
    print("  prices   the archive's adjusted close, and open x adjusted close / close")
    print(f"  Sharpe   sqrt({TRADING_DAYS}) * mean / std, no risk-free rate")
    print()
    header = f"  {'Price and specification':<58}"
    for name in ("S&P 500", "S&P 400", "S&P 600", "control", "unexcl."):
        header += f" {name:>8}"
    print(header)
    specifications = (
        ("before costs", "before_costs"),
        (f"after {cost}, first day uncharged", "after_costs"),
        (f"after {cost}, first day charged", "after_costs_charged"),
    )
    for price, each in (("Closes", result.closes), ("Opens", result.opens)):
        for label, field in specifications:
            line = f"  {price + ', ' + label:<58}"
            for run in (each.large, each.mid, each.small, each.control, each.control_unexcluded):
                line += f" {getattr(run, field):>8.4f}"
            print(line)
    print()
    print("  Before-cost gaps against Memmel's (2003) standard error, iid normal days assumed:")
    for price, each in (("Closes", result.closes), ("Opens", result.opens)):
        print(f"  {price}")
        print(_gap_line("S&P 400 less S&P 500", each.mid_gap))
        print(_gap_line("S&P 600 less S&P 400", each.small_gap))
        print(_gap_line("control less Chan's S&P 600", each.control_gap))
        print(_gap_line("unexcluded less Chan's S&P 600", each.control_gap_unexcluded))
    print()
    for price, each in (("Closes", result.closes), ("Opens", result.opens)):
        mid_step, small_step = (
            "rises" if rises else "does not rise" for rises in pair_directions(each.figures)
        )
        print(
            f"  {price:<7} order {each.order}, S&P 500 to S&P 400 {mid_step}, "
            f"S&P 400 to S&P 600 {small_step}"
        )
        print(
            f"          S&P 400's step to its nearer neighbour {each.nearer_step:.4f}, "
            f"control's gap {abs(each.control_gap.gap):.4f}, "
            f"{abs(each.control_gap_unexcluded.gap):.4f} unexcluded"
        )
    print(
        f"  Control within the step at both prices: {'yes' if result.separable else 'no'}, "
        f"and {'yes' if result.separable_unexcluded else 'no'} without the exclusions."
    )
    print(f"  Reading, declared before any figure: {result.reading}.")
    print(
        f"    The order holding at both prices is {POINTING_CHANS_WAY}, fully reversed at "
        f"both is {POINTING_AGAINST}, and anything else is {MIXED}."
    )
    print(
        "    A control gap wider than the S&P 400's step to its nearer neighbour at either "
        f"price reads as {NOT_SEPARABLE}."
    )
    print(f"    A gap beyond noise is more than {NOISE_MULTIPLE:g} standard errors from 0.")
    print()
    print(
        "  Excluded in the control: the returns of CORSQ on 2006-05-19 and ZD on 2006-05-25, "
        "unadjusted splits, and MAG's price on 2006-01-10, a bad print."
    )
    print("  Kept in the S&P 400: KCI on 2006-08-04, a real traded move.")
    print(
        f"  Khandani and Lo report {BOOK_KHANDANI_LO:.2f} for 2006 on their own universe, "
        "printed and judged against nothing."
    )
    print(
        "  Every panel holds survivors. Chan's files hold the indexes as of 2007-11-23 and "
        "2008-01-14, and the archive panels the holdings Alpha Vantage still serves."
    )
    print(
        f"  Every universe pays the same {cost}, while smaller stocks cost more to trade, "
        "so the after-cost figures flatter the smaller indexes."
    )
    print(
        "  EXPLORATORY. A rule Chan published, run unchanged on stocks his exercise names, "
        "so no figure carries a verdict."
    )


def run(data_dir: Path | None = None, directory: Path | None = None) -> MidCapComparison:
    """Read every panel, run both ladders, and print the report."""
    members, held_tickers, frames = read(data_dir, directory)
    result = comparison(frames)
    report(members, held_tickers, result)
    return result


def main() -> None:
    argparse.ArgumentParser(
        description="Khandani and Lo's linear reversal on the S&P 400, "
        "between Chan's S&P 500 and S&P 600 files"
    ).parse_args()
    try:
        run()
    except (VintageUnavailable, ArchiveUnavailable, ArchiveRefused, PanelRefused) as refusal:
        # One line rather than a traceback, the way chan.khandani_lo_small_caps
        # reports a missing vintage.
        raise SystemExit(str(refusal)) from refusal


if __name__ == "__main__":
    main()
